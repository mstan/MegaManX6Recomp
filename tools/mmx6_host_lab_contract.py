"""Bind the lab rule to its complete canonical semantic/evidence record."""
import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]

def validate_execution_profile(path, expected_identity):
    """Compare the configured runtime, never the contract's generated macro."""
    identities = re.findall(
        r'(?m)^#define[ \t]+PSX_EXECUTION_ID[ \t]+"([0-9a-f]{64})"[ \t]*$',
        Path(path).read_text(encoding="ascii"))
    if len(identities) != 1:
        raise ValueError("configured profile must define exactly one PSX_EXECUTION_ID")
    if identities[0] != expected_identity:
        raise ValueError("lab contract execution identity differs from configured runtime "
                         f"PSX_EXECUTION_ID: {expected_identity} != {identities[0]}")
    return identities[0]


def generated_header():
    record = json.loads((ROOT / "docs/COOP_HOST_LAB_CONTRACT.json").read_text(encoding="utf-8"))
    canonical = json.dumps(record, sort_keys=True, separators=(",", ":"), ensure_ascii=True).encode("ascii")
    digest = hashlib.sha256(canonical).digest()
    return ("/* Generated by tools/mmx6_host_lab_contract.py; no qualification is granted. */\n"
            "#ifndef MMX6_COOP_HOST_LAB_CONTRACT_H\n#define MMX6_COOP_HOST_LAB_CONTRACT_H\n"
            f'#define MMX6_HOST_LAB_PROFILE "{record["profile"]}"\n'
            f'#define MMX6_HOST_LAB_REVISION {record["revision"]}u\n'
            f'#define MMX6_HOST_LAB_TITLE_COMPATIBILITY "{record["session"]["title_compatibility"]}"\n'
            f'#define MMX6_HOST_LAB_EXECUTION_ID "{record["execution"]["identity"]}"\n'
            f'#define MMX6_HOST_LAB_BIOS_ID "{record["bios"]["image_id"]}"\n'
            f'#define MMX6_HOST_LAB_BIOS_WORDSUM {record["bios"]["image_wordsum"]}u\n'
            f'#define MMX6_HOST_LAB_FEATURES {record["execution"]["required_observed_features"]}u\n'
            f'#define MMX6_HOST_LAB_CONTRACT_SHA256 "{digest.hex()}"\n'
            "#define MMX6_HOST_LAB_QUALIFICATION_BYTES {" + ",".join(f"0x{x:02x}" for x in digest) + "}\n#endif\n")


def generated_portable_cpu_header():
    """A separate candidate record leaves the existing 0x7f cell unchanged."""
    record = json.loads((ROOT / "docs/COOP_PORTABLE_CPU_HOST_LAB_CONTRACT.json").read_text(encoding="utf-8"))
    base = json.loads((ROOT / "docs/COOP_HOST_LAB_CONTRACT.json").read_text(encoding="utf-8"))
    def canonical(value):
        return json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=True).encode("ascii")
    if record["base_contract_sha256"] != hashlib.sha256(canonical(base)).hexdigest():
        raise ValueError("portable CPU record must be reviewed against the current unchanged base contract")
    if record["required_optional_features"] != 0 or record["revision"] != 117:
        raise ValueError("portable CPU candidate requires no optional ISA and revision117")
    digest = hashlib.sha256(canonical(record)).digest()
    return ("/* Generated candidate contract; this is not runtime qualification. */\n"
            "#ifndef MMX6_COOP_PORTABLE_CPU_HOST_LAB_CONTRACT_H\n#define MMX6_COOP_PORTABLE_CPU_HOST_LAB_CONTRACT_H\n"
            f'#define MMX6_PORTABLE_CPU_HOST_LAB_PROFILE "{record["profile"]}"\n'
            f'#define MMX6_PORTABLE_CPU_HOST_LAB_REVISION {record["revision"]}u\n'
            "#define MMX6_PORTABLE_CPU_HOST_LAB_QUALIFICATION_BYTES {" + ",".join(f"0x{x:02x}" for x in digest) + "}\n#endif\n")

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--execution-profile", type=Path,
                        help="Actual configure-generated psx_execution/psx-runtime/profile.h")
    args = parser.parse_args()
    if args.execution_profile is not None:
        record = json.loads((ROOT / "docs/COOP_HOST_LAB_CONTRACT.json").read_text(encoding="utf-8"))
        try:
            validate_execution_profile(args.execution_profile, record["execution"]["identity"])
        except (OSError, ValueError) as error:
            parser.error(str(error))
    path = ROOT / "src/mods/mmx6_coop_host_lab_contract.h"
    expected = generated_header()
    if args.write:
        path.write_text(expected, encoding="ascii", newline="\n")
    elif path.read_text(encoding="ascii") != expected:
        raise SystemExit("lab contract/header mismatch; regenerate and review the semantic change")
    portable_path = ROOT / "src/mods/mmx6_coop_portable_cpu_host_lab_contract.h"
    portable_expected = generated_portable_cpu_header()
    if args.write:
        portable_path.write_text(portable_expected, encoding="ascii", newline="\n")
    elif portable_path.read_text(encoding="ascii") != portable_expected:
        raise SystemExit("portable CPU contract/header mismatch; regenerate and review the semantic change")
    print("lab semantic contract: " + hashlib.sha256(json.dumps(json.loads((ROOT / 'docs/COOP_HOST_LAB_CONTRACT.json').read_text()), sort_keys=True, separators=(',', ':'), ensure_ascii=True).encode('ascii')).hexdigest())

if __name__ == "__main__":
    main()
