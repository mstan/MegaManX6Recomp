"""Maintain live X6 coverage without changing the frozen native inventory.

No native extraction, game launch, tracker operation or inherited parity pass.
All receipt files are read as data. Evidence hashing is mandatory, including
historical failed attempts. The record command appends; it never replaces one.
"""
from __future__ import annotations

import argparse
from collections import Counter
import copy
from datetime import datetime
import hashlib
import html
import json
import ntpath
import os
from pathlib import Path
import re
import tempfile

ROOT = Path(__file__).resolve().parents[1]
INVENTORY = ROOT / "docs/COOP_X6_CONTENT.json"
LEDGER = ROOT / "docs/COOP_X6_COVERAGE.json"
MARKDOWN = ROOT / "docs/COOP_X6_COVERAGE.md"
INVENTORY_SHA256 = "67508ae2e19ad07c2c5cad41e12dbeb5e446e4eb50f033efa75ed306f2636fad"
MODES = ("local_coop", "netplay")
STATUSES = ("unverified", "blocked", "failed", "passed", "inapplicable")
LOCATION_CHECKS = ("terrain_collision_scroll", "enemies_interactions", "music_sfx",
                   "checkpoint_retry", "boss", "exit_actual_transition")
REPLOID_CHECKS = ("rescue_p1", "rescue_p2", "simultaneous_contact", "infection_loss",
                 "reward_once", "retry_reentry", "native_card_cold_continue")
GENERATED = "<!-- Generated by tools/mmx6_content_coverage.py; edit the JSON ledger through record. -->"
MAX_JSON_BYTES = 64 * 1024 * 1024


class CoverageError(ValueError):
    pass


def canonical(value) -> bytes:
    try:
        return json.dumps(value, sort_keys=True, separators=(",", ":"),
                          ensure_ascii=True, allow_nan=False).encode("utf-8")
    except (ValueError, TypeError, RecursionError) as exc:
        raise CoverageError(f"noncanonical JSON value: {exc}") from exc


def digest(value: bytes) -> str:
    return hashlib.sha256(value).hexdigest()


def _unique_object(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise CoverageError(f"duplicate JSON key: {key}")
        result[key] = value
    return result


def decode(data: bytes):
    if len(data) > MAX_JSON_BYTES:
        raise CoverageError("JSON exceeds the 64 MiB codec bound")
    def bad_constant(value):
        raise CoverageError(f"non-finite JSON number: {value}")
    try:
        value = json.loads(data, object_pairs_hook=_unique_object,
                           parse_constant=bad_constant)
        canonical(value)  # Finite literals such as1e9999 must not become infinity.
        return value
    except (json.JSONDecodeError, UnicodeDecodeError, RecursionError) as exc:
        raise CoverageError(f"invalid JSON: {exc}") from exc


def read_json(path: Path):
    return decode(path.read_bytes())


def _keys(value, required, optional=(), where="object"):
    if not isinstance(value, dict) or set(value) - set(required) - set(optional) or set(required) - set(value):
        raise CoverageError(f"{where}: required keys {sorted(required)}, optional {sorted(optional)}")


def _text(value, where):
    if not isinstance(value, str) or not value.strip() or "\x00" in value:
        raise CoverageError(f"{where}: nonempty text required")


def _sha(value, width, where):
    if not isinstance(value, str) or not re.fullmatch(f"[0-9a-f]{{{width}}}", value) or value == "0" * width:
        raise CoverageError(f"{where}: exact lowercase {width}-character identity required")


def reject_c_path(value: str):
    # ntpath also catches C:\\... on a non-Windows checker and C:relative paths.
    drive = ntpath.splitdrive(value)[0].replace("/", "\\").lower()
    if drive.endswith("c:") or drive.endswith("\\c$"):
        raise CoverageError("C: evidence/output paths are forbidden")
    if "://" in value or value.lower().startswith("file:"):
        raise CoverageError("artifact/output paths must be filesystem paths, not URLs")


def resolve_path(value: str, root: Path, *, exists=True) -> Path:
    _text(value, "path")
    reject_c_path(value)
    path = Path(value)
    if not path.is_absolute():
        path = root / path
    try:
        path = path.resolve(strict=exists)
    except OSError as exc:
        raise CoverageError(f"cannot resolve path: {value}: {exc}") from exc
    reject_c_path(str(path))  # Also rejects a junction/symlink resolving onto C:.
    return path


def load_inventory(path: Path = INVENTORY) -> dict:
    raw = path.read_bytes()
    if digest(raw) != INVENTORY_SHA256:
        raise CoverageError("frozen inventory SHA256 drift; do not regenerate it over live results")
    report = decode(raw)
    if len(report["campaign_obligations"]) != 23 or len(report["mechanics_obligations"]) != 56:
        raise CoverageError("frozen obligation count drift")
    if len(report["locations"]) != 115 or len(report["reploids"]) != 128:
        raise CoverageError("frozen native location/Reploid count drift")
    return report


def definitions(report: dict) -> list[dict]:
    """Only authored obligations/check keys; no parity-row expansion or inference."""
    rows = []
    for group in ("campaign_obligations", "mechanics_obligations", "locations", "reploids"):
        for index, source in enumerate(report[group]):
            if group.endswith("obligations"):
                if set(source["checks"]) != set(MODES):
                    raise CoverageError("obligation mode definition drift")
                checks = ("obligation",)
            else:
                checks = LOCATION_CHECKS if group == "locations" else REPLOID_CHECKS
                if tuple(source["checks"]) != checks:
                    raise CoverageError("authored check-key definition drift")
            native = {key: copy.deepcopy(value) for key, value in source.items()
                      if key not in ("status", "checks", "evidence")}
            for check in checks:
                case_id = source["id"] if check == "obligation" else source["id"] + "/" + check
                rows.append({"id": case_id, "definition": {
                    "inventory_pointer": f"/{group}/{index}", "family": group,
                    "check_key": check, "native": native}})
    if len(rows) != 1665 or len({row["id"] for row in rows}) != 1665:
        raise CoverageError("expected exactly 1665 distinct authored check cases")
    return rows


def inventory_identity(report):
    return {"sha256": INVENTORY_SHA256, "source_sha256": report["source_sha256"],
            "bin_sha256": report["bin_sha256"],
            "definitions_sha256": digest(canonical(definitions(report)))}


def initial_ledger(report: dict) -> dict:
    rows = definitions(report)
    for row in rows:
        row["modes"] = {mode: {"status": "unverified", "attempts": []} for mode in MODES}
    return {"format_version": 1, "inventory": inventory_identity(report), "cases": rows}


class Artifacts:
    """Fresh invocation-local hashes, never a persistent metadata/hash cache."""
    def __init__(self, root: Path):
        self.root = root
        self.hashes = {}
        self.paths = set()

    def check(self, artifact: dict) -> Path:
        _keys(artifact, ("path", "sha256"), ("role",), "artifact")
        _sha(artifact["sha256"], 64, "artifact SHA256")
        if "role" in artifact:
            _text(artifact["role"], "artifact role")
        path = resolve_path(artifact["path"], self.root)
        if not path.is_file():
            raise CoverageError(f"artifact is not a regular file: {path}")
        if path not in self.hashes:
            h = hashlib.sha256()
            with path.open("rb") as stream:
                for block in iter(lambda: stream.read(1024 * 1024), b""):
                    h.update(block)
            self.hashes[path] = h.hexdigest()
        if self.hashes[path] != artifact["sha256"]:
            raise CoverageError(f"artifact SHA256 mismatch: {path}")
        self.paths.add(path)
        return path


def validate_receipt(receipt: dict, case_id: str, mode: str,
                     native_sources: set[str], artifacts: Artifacts):
    required = ("case_id", "mode", "result", "candidate", "recorded_at", "build_identity",
                "settings", "action", "outcome", "artifacts", "limits", "bypasses")
    _keys(receipt, required, ("native_absence",), "receipt")
    if receipt["case_id"] != case_id or receipt["mode"] != mode:
        raise CoverageError("receipt case/mode does not match its owning result")
    if receipt["result"] not in STATUSES:
        raise CoverageError("invalid receipt result")
    _sha(receipt["candidate"], 40, "candidate")
    try:
        if not re.fullmatch(r"\d{4}-\d\d-\d\dT\d\d:\d\d:\d\dZ", receipt["recorded_at"]):
            raise ValueError()
        datetime.strptime(receipt["recorded_at"], "%Y-%m-%dT%H:%M:%SZ")
    except (ValueError, TypeError):
        raise CoverageError("receipt recorded_at must be a UTC second timestamp") from None
    build = receipt["build_identity"]
    _keys(build, ("name", "image"), ("details",), "build_identity")
    _text(build["name"], "build name")
    artifacts.check(build["image"])
    if resolve_path(build["image"]["path"], artifacts.root).stat().st_size == 0:
        raise CoverageError("build image must be nonempty")
    if "details" in build and not isinstance(build["details"], dict):
        raise CoverageError("build details must be an object")
    if not isinstance(receipt["settings"], dict) or not receipt["settings"]:
        raise CoverageError("receipt needs explicit effective settings")
    for field in ("action", "outcome"):
        _text(receipt[field], field)
    for field in ("limits", "bypasses"):
        if not isinstance(receipt[field], list):
            raise CoverageError(f"receipt {field} must be an explicit list, possibly empty")
        for item in receipt[field]:
            _text(item, field)
    if not isinstance(receipt["artifacts"], list) or not receipt["artifacts"]:
        raise CoverageError("every attempted result needs retained evidence artifacts")
    evidence_paths = [artifacts.check(item) for item in receipt["artifacts"]]
    if len(evidence_paths) != len(set(evidence_paths)):
        raise CoverageError("duplicate evidence artifact")
    if receipt["result"] == "inapplicable":
        absence = receipt.get("native_absence")
        _keys(absence, ("kind", "case_id", "source", "audit", "source_reference", "reason"), where="native_absence")
        if absence["kind"] != "authored_native_content_absent" or absence["case_id"] != case_id:
            raise CoverageError("inapplicable requires case-specific authored native absence, not unknown/unimplemented")
        for field in ("source_reference", "reason"):
            _text(absence[field], "native absence " + field)
        _keys(absence["source"], ("path", "sha256"), ("role",), "native source artifact")
        _sha(absence["source"]["sha256"], 64, "native source SHA256")
        if absence["source"]["sha256"] not in native_sources:
            raise CoverageError("native absence source must match the frozen original EXE/BIN identity")
        source_path = artifacts.check(absence["source"])
        audit_path = artifacts.check(absence["audit"])
        if audit_path == source_path:
            raise CoverageError("native absence needs a separate retained source audit")
        if audit_path not in evidence_paths:
            raise CoverageError("native absence audit must be retained in receipt artifacts")
    elif "native_absence" in receipt:
        raise CoverageError("native_absence is only valid for an inapplicable result")
    canonical(receipt)  # Also refuses non-finite values in programmatic callers.


def validate_ledger(ledger: dict, report: dict, artifact_root: Path = ROOT) -> Artifacts:
    _keys(ledger, ("format_version", "inventory", "cases"), where="ledger")
    if type(ledger["format_version"]) is not int or ledger["format_version"] != 1:
        raise CoverageError("unsupported live coverage format")
    if ledger["inventory"] != inventory_identity(report):
        raise CoverageError("ledger inventory/definitions identity drift")
    expected = definitions(report)
    if not isinstance(ledger["cases"], list) or len(ledger["cases"]) != len(expected):
        raise CoverageError("missing or invented coverage cases")
    artifacts = Artifacts(artifact_root)
    native_sources = {report["source_sha256"], report["bin_sha256"]}
    seen_attempts = set()
    for row, definition in zip(ledger["cases"], expected):
        _keys(row, ("id", "definition", "modes"), where="case")
        if row["id"] != definition["id"] or row["definition"] != definition["definition"]:
            raise CoverageError(f"missing/duplicate/invented/changed/reordered definition: {definition['id']}")
        _keys(row["modes"], MODES, where=f"{row['id']} modes")
        for mode in MODES:
            result = row["modes"][mode]
            _keys(result, ("status", "attempts"), where="mode result")
            if result["status"] not in STATUSES or not isinstance(result["attempts"], list):
                raise CoverageError("invalid mode status/history")
            for attempt in result["attempts"]:
                _keys(attempt, ("receipt", "sha256"), where="attempt")
                _sha(attempt["sha256"], 64, "receipt SHA256")
                if digest(canonical(attempt["receipt"])) != attempt["sha256"]:
                    raise CoverageError("retained receipt SHA256 mismatch")
                if attempt["sha256"] in seen_attempts:
                    raise CoverageError("duplicate retained attempt")
                seen_attempts.add(attempt["sha256"])
                validate_receipt(attempt["receipt"], row["id"], mode, native_sources, artifacts)
            current = result["attempts"][-1]["receipt"]["result"] if result["attempts"] else "unverified"
            if result["status"] != current:
                raise CoverageError("mode status must equal its latest retained attempt; empty history is unverified")
    return artifacts


def aggregate(row: dict) -> tuple[str, str]:
    modes = [row["modes"][mode] for mode in MODES]
    statuses = [mode["status"] for mode in modes]
    if "failed" in statuses:
        return "failed", "a current mode failed"
    if "blocked" in statuses:
        return "blocked", "a current mode is blocked"
    if statuses in (["passed", "passed"], ["inapplicable", "inapplicable"]):
        latest = [mode["attempts"][-1]["receipt"] for mode in modes]
        if len({r["candidate"] for r in latest}) != 1:
            return "unverified", "latest modes use different candidates"
        if len({r["build_identity"]["image"]["sha256"] for r in latest}) != 1:
            return "unverified", "latest modes use different actual build images"
        return statuses[0], "both latest mode receipts agree on exact candidate and build image"
    return "unverified", "both independent modes are not complete with the same result"


def append_receipt(ledger: dict, receipt: dict, report: dict, artifact_root: Path = ROOT) -> dict:
    validate_ledger(ledger, report, artifact_root)
    _keys(receipt, ("case_id", "mode", "result", "candidate", "recorded_at", "build_identity",
                    "settings", "action", "outcome", "artifacts", "limits", "bypasses"), ("native_absence",), "receipt")
    if receipt["mode"] not in MODES:
        raise CoverageError("unknown receipt mode")
    result = copy.deepcopy(ledger)
    row = next((row for row in result["cases"] if row["id"] == receipt["case_id"]), None)
    if row is None:
        raise CoverageError("receipt names an invented coverage case")
    mode = row["modes"][receipt["mode"]]
    mode["attempts"].append({"receipt": copy.deepcopy(receipt), "sha256": digest(canonical(receipt))})
    mode["status"] = receipt["result"]
    validate_ledger(result, report, artifact_root)
    return result


def encoded(value) -> bytes:
    return (json.dumps(value, indent=2, ensure_ascii=True, allow_nan=False) + "\n").encode("utf-8")


def initialize(path: Path, report: dict):
    original_path = path if path.is_absolute() else ROOT / path
    if original_path.exists() or original_path.is_symlink():
        raise FileExistsError(f"existing coverage destination: {original_path}")
    path = resolve_path(str(path), ROOT, exists=False)
    value = initial_ledger(report)
    validate_ledger(value, report)
    # No force option: an existing file, including an empty file, is never reset.
    with path.open("xb") as output:
        output.write(encoded(value))


def record(path: Path, receipt: dict, report: dict, artifact_root: Path = ROOT):
    path = resolve_path(str(path), ROOT)
    lock = path.with_name(path.name + ".lock")
    try:
        handle = lock.open("xb")
    except FileExistsError:
        raise CoverageError("ledger is locked; preserve the existing operation/lock") from None
    temporary = None
    try:
        with handle:
            original = path.read_bytes()
            value = append_receipt(decode(original), receipt, report, artifact_root)
            if path in validate_ledger(value, report, artifact_root).paths:
                raise CoverageError("a mutable ledger cannot be its own evidence/build artifact")
            with tempfile.NamedTemporaryFile(dir=path.parent, prefix=path.name + ".", suffix=".tmp", delete=False) as output:
                temporary = Path(output.name)
                output.write(encoded(value))
                output.flush()
                os.fsync(output.fileno())
            if path.read_bytes() != original:
                raise CoverageError("ledger changed during record; refusing to overwrite it")
            os.replace(temporary, path)
            temporary = None
    finally:
        if temporary is not None:
            temporary.unlink()
        lock.unlink()


def _md(value) -> str:
    value = html.escape(str(value), quote=False).replace("\r", "").replace("\n", " / ")
    return value.replace("|", "\\|").replace("`", "\\`").replace("[", "\\[").replace("]", "\\]")


def render(ledger: dict) -> str:
    counts = Counter(aggregate(row)[0] for row in ledger["cases"])
    mode_counts = {mode: Counter(row["modes"][mode]["status"] for row in ledger["cases"]) for mode in MODES}
    lines = [GENERATED, "# X6 live content coverage", "",
             "The native inventory is immutable. This ledger tracks its existing 1,665 cases and 3,330 independent mode results; it inherits no parity-row passes.", "",
             f"Frozen inventory SHA256: `{ledger['inventory']['sha256']}`.", "",
             "Aggregate pass requires the latest local co-op and netplay attempts to pass on the same candidate40 and actual build-image SHA256. Receipt structure and hashes do not prove that a native claim is true; reviewers must inspect its action, outcome, limits and bypasses.", "",
             "| Result | Aggregate cases | Local co-op | Netplay |", "| --- | ---: | ---: | ---: |"]
    for state in STATUSES:
        lines.append(f"| {state} | {counts[state]} | {mode_counts['local_coop'][state]} | {mode_counts['netplay'][state]} |")
    lines += ["", "All attempted histories, including failures superseded by a later candidate, remain in JSON and below. Source-backed native absence is required for inapplicable; missing implementation or unknown reachability is unverified/blocked.", "",
              "Validate: `python tools/mmx6_content_coverage.py check`. Regenerate this view: `python tools/mmx6_content_coverage.py render`. Neither command rewrites the JSON ledger or extracts native data.", ""]
    for family in ("campaign_obligations", "mechanics_obligations", "locations", "reploids"):
        lines += ["## " + family.replace("_", " ").capitalize(), "", "| Existing case | Native definition | Local co-op | Netplay | Aggregate | Attempts |", "| --- | --- | --- | --- | --- | ---: |"]
        for row in ledger["cases"]:
            definition = row["definition"]
            if definition["family"] != family:
                continue
            native = definition["native"]
            label = native.get("title") or (f"stage {native['stage']}/section {native['section']}; " +
                    (f"checkpoint {native['checkpoint']}; record {native['record']}" if family == "locations" else f"Reploid {native['native_id']}; record {native['address']}"))
            state, reason = aggregate(row)
            count = sum(len(row["modes"][mode]["attempts"]) for mode in MODES)
            aggregate_text = state + ": " + reason if state == "unverified" and count else state
            lines.append(f"| {_md(row['id'])} | {_md(label)} | {row['modes']['local_coop']['status']} | {row['modes']['netplay']['status']} | {_md(aggregate_text)} | {count} |")
        lines.append("")
    attempted = [row for row in ledger["cases"] if any(row["modes"][mode]["attempts"] for mode in MODES)]
    lines += ["## Retained attempt history", ""]
    if not attempted:
        lines += ["No attempts recorded. All results remain unverified.", ""]
    for row in attempted:
        lines += ["### " + _md(row["id"]), ""]
        for mode in MODES:
            for index, attempt in enumerate(row["modes"][mode]["attempts"], 1):
                receipt = attempt["receipt"]
                lines += [f"- {mode} attempt {index}: **{receipt['result']}**, {_md(receipt['recorded_at'])}; candidate `{receipt['candidate']}`; receipt SHA256 `{attempt['sha256']}`.",
                          "  Build: " + _md(json.dumps(receipt["build_identity"], sort_keys=True)),
                          "  Settings: " + _md(json.dumps(receipt["settings"], sort_keys=True)),
                          "  Action: " + _md(receipt["action"]), "  Outcome: " + _md(receipt["outcome"]),
                          "  Artifacts: " + _md(json.dumps(receipt["artifacts"], sort_keys=True)),
                          "  Limits: " + _md(json.dumps(receipt["limits"])), "  Bypasses: " + _md(json.dumps(receipt["bypasses"]))]
                if "native_absence" in receipt:
                    lines.append("  Native absence: " + _md(json.dumps(receipt["native_absence"], sort_keys=True)))
                lines.append("")
    return "\n".join(lines)


def write_render(path: Path, ledger_path: Path, inventory_path: Path, ledger: dict, artifacts: Artifacts):
    path = resolve_path(str(path), ROOT, exists=False)
    protected = {ledger_path.resolve(), inventory_path.resolve()} | artifacts.paths
    if path in protected:
        raise CoverageError("render output would overwrite a ledger, inventory or evidence artifact")
    if path.exists():
        with path.open("rb") as current:
            if current.readline(len(GENERATED.encode("utf-8")) + 3).rstrip(b"\r\n") != GENERATED.encode("utf-8"):
                raise CoverageError("render refuses to overwrite a file without its generated-view marker")
    value = render(ledger).encode("utf-8")
    if not path.exists():
        with path.open("xb") as output:
            output.write(value)
    else:
        path.write_bytes(value)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--inventory", type=Path, default=INVENTORY)
    parser.add_argument("--ledger", type=Path, default=LEDGER)
    parser.add_argument("--artifact-root", type=Path, default=ROOT,
                        help="base for relative artifact paths; hashes are always checked")
    commands = parser.add_subparsers(dest="command", required=True)
    commands.add_parser("initialize", help="exclusively create an all-unverified ledger; never reset")
    commands.add_parser("check", help="read-only definitions, history, receipt and artifact validation")
    view = commands.add_parser("render", help="validate, then update only the generated Markdown view")
    view.add_argument("--out", type=Path, default=MARKDOWN)
    append = commands.add_parser("record", help="append one complete receipt; retain all failed attempts")
    append.add_argument("--receipt", type=Path, required=True)
    args = parser.parse_args(argv)
    try:
        report = load_inventory(args.inventory)
        if args.command == "initialize":
            initialize(args.ledger, report)
        elif args.command == "record":
            record(args.ledger, read_json(args.receipt), report, args.artifact_root)
        else:
            ledger = read_json(args.ledger)
            artifacts = validate_ledger(ledger, report, args.artifact_root)
            if args.command == "render":
                write_render(args.out, args.ledger, args.inventory, ledger, artifacts)
        print(f"X6 coverage {args.command}: valid; 1665 existing cases, 3330 mode results")
        return 0
    except (CoverageError, OSError, TypeError, KeyError, RecursionError) as exc:
        parser.exit(1, f"X6 coverage refused: {exc}\n")


if __name__ == "__main__":
    raise SystemExit(main())
